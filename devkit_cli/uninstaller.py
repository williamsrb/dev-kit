"""The detached uninstaller, written to $HOME/.local/bin at install time.

The checkout does not contain a shell file. Every command that materializes a
profile writes the text below to devkit-uninstall.sh, so a machine can always
be undone by the command that is already on PATH.
"""

from __future__ import annotations

from pathlib import Path

from .common import Plan

SCRIPT = r"""
#!/usr/bin/env bash
# Remove what devkit installed, then delete this command if it lives
# under $HOME/.local/bin. install.py writes this file. The checkout has no copy.
#
# A path that was never created is skipped. This exits 0 when nothing was
# installed. The checkout, $HOME/.agents, and packages from bootstrap.sh stay.
#
#   devkit-uninstall.sh            # dry run
#   devkit-uninstall.sh --apply    # remove, then ask sudo for root-owned files
#   devkit-uninstall.sh --user NAME --apply
set -euo pipefail

PATH_COMMENT='# Added by devkit bootstrap.sh'
PATH_EXPORT='export PATH="$HOME/.local/bin:$PATH"'
MARKER='Generated by devkit'
IGNORE_BEGIN='# Added by devkit: regenerable harness output, any depth.'
IGNORE_END='# End of devkit block.'
APPLY=0
TARGET_USER=""

FORK_ROOT=/usr/lib/devkit
WORKER=/usr/local/bin/sync-devkit-profile-apps.py
APT_CONF=/etc/apt/apt.conf.d/99-devkit-profile-apps
DPKG_CONF=/etc/dpkg/dpkg.cfg.d/60devkit-profile-apps
LOG_PATH=/var/log/devkit-profile-apps.log
APPARMOR_DIR=/etc/apparmor.d

usage() {
  echo "usage: devkit-uninstall.sh [--apply] [--user NAME]"
}

die() {
  echo "error: $*" >&2
  exit 2
}

# --root-only is the elevated half. It is not a user command.
if [[ "${1:-}" == "--root-only" ]]; then
  [[ "$(id -u)" -eq 0 ]] || die "--root-only must run as root; re-run devkit-uninstall.sh --apply"
  shift
  for path in "$@"; do
    case "$path" in
      "$FORK_ROOT"|"$FORK_ROOT"/*|"$WORKER"|"$APT_CONF"|"$DPKG_CONF"|"$LOG_PATH")
        ;;
      "$APPARMOR_DIR"/devkit-*)
        if command -v apparmor_parser >/dev/null 2>&1 && [[ -f "$path" ]]; then
          apparmor_parser -R "$path" >/dev/null 2>&1 || true
        fi
        ;;
      *)
        die "refusing to remove $path"
        ;;
    esac
    if [[ -L "$path" || -f "$path" ]]; then
      rm -f "$path"
    elif [[ -d "$path" ]]; then
      rm -rf "$path"
    fi
  done
  exit 0
fi

while [[ $# -gt 0 ]]; do
  case "$1" in
    --apply) APPLY=1; shift ;;
    --user)
      [[ $# -ge 2 ]] || die "--user needs an account name"
      TARGET_USER=$2
      shift 2
      ;;
    -h|--help) usage; exit 0 ;;
    *) die "unrecognized argument: $1" ;;
  esac
done

if [[ "$(id -u)" -eq 0 && -z "$TARGET_USER" ]]; then
  die "refusing to uninstall as root; re-run as the account that owns the profiles, or pass --user NAME"
fi

if [[ -n "$TARGET_USER" ]]; then
  target_uid=$(id -u "$TARGET_USER" 2>/dev/null || true)
  [[ "$target_uid" == "0" ]] && die "refusing to uninstall uid 0"
  HOME="$(getent passwd "$TARGET_USER" | cut -d: -f6)"
  [[ -n "$HOME" && -d "$HOME" ]] || die "no such user: $TARGET_USER"
  export HOME
fi

FOUND=0
HEADER_DONE=0
declare -A SEEN=()

note() {
  if [[ "$HEADER_DONE" -eq 0 ]]; then
    if [[ "$APPLY" -eq 1 ]]; then
      echo "Removing devkit install state:"
    else
      echo "Would remove devkit install state:"
    fi
    HEADER_DONE=1
  fi
  printf '  %s\n' "$1"
  FOUND=1
}

remove_file() {
  local path=$1
  if [[ -z "${SEEN[$path]:-}" && ( -e "$path" || -L "$path" ) ]]; then
    SEEN[$path]=1
    note "file  $path"
    if [[ "$APPLY" -eq 1 ]]; then
      rm -f "$path"
    fi
  fi
  local backup
  shopt -s nullglob
  for backup in "$path".devkit-backup-*; do
    if [[ -z "${SEEN[$backup]:-}" ]]; then
      SEEN[$backup]=1
      note "file  $backup"
      if [[ "$APPLY" -eq 1 ]]; then
        rm -f "$backup"
      fi
    fi
  done
  shopt -u nullglob
}

remove_dir() {
  local path=$1
  if [[ -d "$path" && ! -L "$path" ]]; then
    note "dir   $path"
    if [[ "$APPLY" -eq 1 ]]; then
      rm -rf "$path"
    fi
  fi
}

strip_path_block() {
  local file=$1
  [[ -f "$file" ]] || return 0
  grep -q -F "$PATH_COMMENT" "$file" || return 0
  grep -q -F "$PATH_EXPORT" "$file" || return 0
  note "strip PATH block  $file"
  [[ "$APPLY" -eq 1 ]] || return 0
  local tmp
  tmp=$(mktemp)
  awk -v comment="$PATH_COMMENT" -v export_line="$PATH_EXPORT" '
    {
      lines[NR] = $0
    }
    END {
      n = 0
      for (i = 1; i <= NR; i++) {
        if (lines[i] == comment && i < NR && lines[i + 1] == export_line) {
          if (n > 0 && out[n] == "") n--
          i++
          continue
        }
        out[++n] = lines[i]
      }
      for (i = 1; i <= n; i++) print out[i]
    }
  ' "$file" >"$tmp"
  mv "$tmp" "$file"
}

# Same lookup as globalignore.target: core.excludesFile, else git's default.
global_ignore_file() {
  local configured
  configured=$(git config --global --get core.excludesFile 2>/dev/null || true)
  case "$configured" in
    "") printf '%s\n' "${XDG_CONFIG_HOME:-$HOME/.config}/git/ignore" ;;
    \~/*) printf '%s\n' "$HOME/${configured#\~/}" ;;
    /*) printf '%s\n' "$configured" ;;
    *) printf '%s\n' "$HOME/$configured" ;;
  esac
}

strip_ignore_block() {
  local file
  file=$(global_ignore_file)
  [[ -f "$file" ]] || return 0
  grep -q -x -F "$IGNORE_BEGIN" "$file" || return 0
  # Without its end line the block has no bounds; stripping would eat the rest.
  grep -q -x -F "$IGNORE_END" "$file" || return 0
  note "strip ignore block  $file"
  [[ "$APPLY" -eq 1 ]] || return 0
  local tmp
  tmp=$(mktemp)
  awk -v begin="$IGNORE_BEGIN" -v end="$IGNORE_END" '
    {
      lines[NR] = $0
    }
    END {
      n = 0
      skip = 0
      for (i = 1; i <= NR; i++) {
        if (!skip && lines[i] == begin) {
          if (n > 0 && out[n] == "") n--
          skip = 1
          continue
        }
        if (skip) {
          if (lines[i] == end) skip = 0
          continue
        }
        out[++n] = lines[i]
      }
      for (i = 1; i <= n; i++) print out[i]
    }
  ' "$file" >"$tmp"
  # cat, not mv: the file may be a symlink into a dotfiles repo.
  cat "$tmp" >"$file"
  rm -f "$tmp"
}

restore_auth() {
  local state="$HOME/.local/state/devkit/auth-handlers.json"
  local apps="$HOME/.local/share/applications"
  local launch="$HOME/.local/bin/devkit-auth-launch"
  local dispatch="$HOME/.local/bin/devkit-auth-dispatch"
  local pending="$HOME/.local/state/devkit/pending-auth.json"
  local installed=0
  [[ -f "$launch" || -f "$dispatch" || -f "$state" || -f "$pending" ]] && installed=1
  if [[ -d "$apps" ]] && compgen -G "$apps/devkit-auth-*.desktop" >/dev/null; then
    installed=1
  fi
  [[ "$installed" -eq 1 ]] || return 0
  note "restore stock URL handlers"
  [[ "$APPLY" -eq 1 ]] || return 0
  command -v xdg-mime >/dev/null 2>&1 || return 0
  local -a schemes=(
    "claude com.anthropic.Claude.desktop"
    "claude-cli claude-code-url-handler.desktop"
    "codex chatgpt.desktop"
    "codex-browser-sidebar chatgpt.desktop"
    "cursor cursor-url-handler.desktop"
  )
  local pair scheme desktop
  for pair in "${schemes[@]}"; do
    scheme=${pair%% *}
    desktop=${pair#* }
    if [[ -f "$state" ]]; then
      local stored
      stored=$(sed -n "s/.*\"$scheme\"[[:space:]]*:[[:space:]]*\"\\([^\"]*\\)\".*/\\1/p" "$state" | head -1 || true)
      [[ -n "$stored" ]] && desktop=$stored
    fi
    XDG_CONFIG_HOME="$HOME/.config" XDG_DATA_HOME="$HOME/.local/share" \
      xdg-mime default "$desktop" "x-scheme-handler/$scheme" >/dev/null 2>&1 || true
  done
}

scan_marked() {
  local dir=$1 entry base
  [[ -d "$dir" ]] || return 0
  shopt -s nullglob
  for entry in "$dir"/*; do
    [[ -f "$entry" && ! -L "$entry" ]] || continue
    base=$(basename "$entry")
    [[ "$base" == "devkit-uninstall.sh" ]] && continue
    grep -q -F "$MARKER" "$entry" 2>/dev/null || continue
    if [[ "$dir" == "$HOME/.local/share/applications" ]]; then
      icons_from_desktop "$entry"
      user_data_from_desktop "$entry"
    fi
    remove_file "$entry"
  done
  shopt -u nullglob
}

icons_from_desktop() {
  local desktop=$1 stem icon_root icon
  [[ -f "$desktop" ]] || return 0
  stem=$(sed -n 's/^Icon=//p' "$desktop" | head -1 || true)
  [[ -n "$stem" && "$stem" != */* ]] || return 0
  icon_root="$HOME/.local/share/icons/hicolor"
  [[ -d "$icon_root" ]] || return 0
  while IFS= read -r icon; do
    remove_file "$icon"
  done < <(find "$icon_root" -name "$stem.png" -type f 2>/dev/null || true)
}

user_data_from_desktop() {
  local desktop=$1 raw path name
  [[ -f "$desktop" ]] || return 0
  raw=$(grep -oE -- '--user-data-dir=[^[:space:]]+|CODEX_ELECTRON_USER_DATA_PATH=[^[:space:]]+' "$desktop" | head -1 || true)
  [[ -n "$raw" ]] || return 0
  path=${raw#*=}
  name=$(basename "$path")
  [[ "$(dirname "$path")" == "$HOME/.config" ]] || return 0
  case "$name" in
    Claude-*|Codex-*|Cursor-*) remove_dir "$path" ;;
  esac
}

collect_profiles() {
  local root="$HOME/.agents-profiles" profile name vendor app data wrapper desktop icon
  [[ -d "$root" ]] || return 0
  shopt -s nullglob
  for profile in "$root"/*; do
    [[ -d "$profile" && ! -L "$profile" ]] || continue
    name=$(basename "$profile")
    [[ "$name" == .* ]] && continue
    for vendor in claude codex cursor; do
      case "$vendor" in
        claude) app=Claude ;;
        codex) app=Codex ;;
        cursor) app=Cursor ;;
      esac
      wrapper="$HOME/.local/bin/${vendor}-${name}"
      desktop="$HOME/.local/share/applications/${app}-${name}.desktop"
      icon="$HOME/.local/share/icons/hicolor/512x512/apps/${vendor}-${name}.png"
      data="$HOME/.config/${app}-${name}"
      remove_file "$wrapper"
      if [[ -f "$desktop" ]]; then
        icons_from_desktop "$desktop"
        user_data_from_desktop "$desktop"
      fi
      remove_file "$desktop"
      remove_file "$icon"
      remove_dir "$data"
    done
  done
  shopt -u nullglob
  remove_dir "$root"
}

root_targets() {
  local path
  for path in "$FORK_ROOT" "$WORKER" "$APT_CONF" "$DPKG_CONF" "$LOG_PATH"; do
    if [[ -e "$path" || -L "$path" ]]; then
      echo "$path"
    fi
  done
  if [[ -d "$APPARMOR_DIR" ]]; then
    shopt -s nullglob
    for path in "$APPARMOR_DIR"/devkit-*; do
      echo "$path"
    done
    shopt -u nullglob
  fi
}

elevate() {
  echo "These steps need administrator privileges: they remove /usr/lib/devkit, the apt/dpkg hooks, and the sync worker."
  local path
  for path in "$@"; do
    echo "  remove $path"
  done
  echo "Asking for administrator privileges."
  local -a cmd
  if [[ -t 0 || -t 1 ]]; then
    command -v sudo >/dev/null 2>&1 || die "sudo is not on PATH"
    cmd=(sudo -- "$0" --root-only "$@")
  elif command -v pkexec >/dev/null 2>&1; then
    cmd=(pkexec "$0" --root-only "$@")
  elif command -v sudo >/dev/null 2>&1; then
    cmd=(sudo -A -- "$0" --root-only "$@")
  else
    die "pkexec and sudo are not on PATH"
  fi
  echo "  + ${cmd[*]}"
  "${cmd[@]}"
}

self_delete() {
  local me
  me=$(readlink -f "$0" 2>/dev/null || printf '%s' "$0")
  case "$me" in
    */.local/bin/devkit-uninstall.sh) rm -f "$me" ;;
  esac
}

restore_auth
for rc in .bash_profile .profile .zshrc .bashrc; do
  strip_path_block "$HOME/$rc"
done
strip_ignore_block
collect_profiles
scan_marked "$HOME/.local/bin"
scan_marked "$HOME/.local/share/applications"
remove_file "$HOME/.local/bin/devkit-auth-launch"
remove_file "$HOME/.local/bin/devkit-auth-dispatch"
remove_dir "$HOME/.local/state/devkit"

mapfile -t ROOTS < <(root_targets)
if [[ "$APPLY" -eq 0 ]]; then
  if [[ ${#ROOTS[@]} -gt 0 ]]; then
    for path in "${ROOTS[@]}"; do
      note "root  $path"
    done
  fi
  if [[ "$FOUND" -eq 0 ]]; then
    echo "uninstall: nothing to remove."
    exit 0
  fi
  echo
  echo "Dry run. Re-run with --apply to remove."
  exit 0
fi

if [[ ${#ROOTS[@]} -gt 0 ]]; then
  elevate "${ROOTS[@]}" && rc=0 || rc=$?
  if [[ "$rc" -ne 0 ]]; then
    echo "note: root-owned devkit files were not removed (exit $rc)."
    echo "      Re-run: devkit-uninstall.sh --apply"
    exit "$rc"
  fi
fi

self_delete
if [[ "$FOUND" -eq 0 && ${#ROOTS[@]} -eq 0 ]]; then
  echo "uninstall: nothing to remove."
else
  echo "uninstall: removed."
fi
exit 0
"""

DEST_NAME = "devkit-uninstall.sh"


def _text() -> str:
    text = SCRIPT.lstrip("\n")
    return text if text.endswith("\n") else text + "\n"


def write_uninstaller(dest: Path) -> None:
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(_text(), encoding="utf-8")
    dest.chmod(0o755)


def ensure(home: Path, plan: Plan) -> None:
    """Record the uninstaller, and write it on --apply.

    Every path that creates a profile calls this. A profile created without it
    would be removable only by hand.
    """
    dest = home / ".local" / "bin" / DEST_NAME
    if dest.is_file() and dest.read_text(encoding="utf-8") == _text():
        return
    plan.record(f"write  {dest}")
    if plan.apply:
        write_uninstaller(dest)
