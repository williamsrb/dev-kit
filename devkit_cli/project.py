"""`devkit project`: apply the harness (skills, instructions) to a work repo.

A profile carries how the agent runs (hooks, MCP, auth, env). A project carries
what the agent knows: the skills of the named profile types, optional repo-owned
skills, and an AGENTS.md. Everything is read from the installed kit; nothing is
installed and nothing outside the repo is written.

Layout, the same one extract-kit uses:

    .agents/skills/<n>  -> <kit home>/current/core/skills/<n>   (base, excluded)
                        -> ../../harness/skills/<n>            (repo-owned)
    .claude/skills/<n>  -> ../../.agents/skills/<n>
    AGENTS.md           (only when the repo has neither AGENTS.md nor CLAUDE.md)
    CLAUDE.md           -> AGENTS.md
    .devkit-project.json  stamp: what the build wrote

Generated paths go into a managed block of `.git/info/exclude`, so a client repo
keeps a clean `git status` and no tracked file is touched. Repo-owned links are
not excluded: the repo owns them and may commit them.
"""

from __future__ import annotations

import hashlib
import json
import os
import re
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path

from . import kithome, manifest, privilege
from .common import FILE_MODE, Plan, ensure_dir, load_json, write_json
from .errors import DevkitError

SCHEMA = 1
CONFIG_REL = "harness/project.json"
OWN_SKILLS_REL = "harness/skills"
OWN_INSTRUCTIONS_REL = "harness/AGENTS.md"
STAMP_REL = ".devkit-project.json"
AGENTS_SKILLS = ".agents/skills"
CLAUDE_SKILLS = ".claude/skills"
INSTRUCTIONS = "AGENTS.md"
INSTRUCTIONS_LINK = "CLAUDE.md"
GENERATED_HEADER = ("<!-- Generated by `devkit project build`. "
                    "Edit harness/AGENTS.md, not this file. -->\n")

_NAME = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.-]*$")
# Directories the build creates links in. One that is a link or a file is left
# alone, so a write can never follow a link out of the repo.
_GUARDED_DIRS = (".agents", AGENTS_SKILLS, ".claude", CLAUDE_SKILLS)
_PRUNE_DIRS = (AGENTS_SKILLS, ".agents", CLAUDE_SKILLS, ".claude")


# ----------------------------------------------------------------- config

@dataclass(frozen=True)
class Config:
    layers: tuple[str, ...]


def load_config(repo: Path, config_path: str | os.PathLike[str] | None = None) -> Config:
    path = Path(config_path) if config_path else repo / CONFIG_REL
    if not path.is_file():
        raise DevkitError(
            f"no project config at {path}",
            f"devkit project init {repo} --layer core --apply   (or pass --config FILE)")
    data = load_json(path, "project config")
    if not isinstance(data, dict) or data.get("schema") != SCHEMA:
        raise DevkitError(f"{path} must be an object with \"schema\": {SCHEMA}",
                          f'write {{"schema": {SCHEMA}, "layers": ["core"]}}')
    layers = data.get("layers")
    if not (isinstance(layers, list) and layers
            and all(isinstance(x, str) and _NAME.match(x) for x in layers)):
        raise DevkitError(f"{path}: \"layers\" must be a non-empty list of profile type names",
                          'e.g. "layers": ["core", "enonic"]')
    return Config(tuple(dict.fromkeys(layers)))


@dataclass(frozen=True)
class Resolved:
    skills: tuple[str, ...]
    lineage: frozenset[str]


def resolve_layers(layers: tuple[str, ...] | list[str], kit_root: Path) -> Resolved:
    """Union of the skills of every named profile type, in layer order.

    Each type goes through `manifest.load`, so `extends` still composes inside
    it and an unknown type raises the error that lists the kit's profiles.
    """
    skills: list[str] = []
    lineage: set[str] = set()
    for layer in layers:
        profile = manifest.load(layer, kit_root=kit_root)
        lineage.update(profile.get("lineage", []))
        for entry in profile.get("skills", []):
            leaf = manifest.layer_leaf(entry)
            if leaf and leaf not in skills and (kit_root / "core" / "skills" / leaf).exists():
                skills.append(leaf)
    return Resolved(tuple(skills), frozenset(lineage))


# -------------------------------------------------------------------- kit

@dataclass(frozen=True)
class Kit:
    root: Path      # the tree being read
    link: Path      # `current`, the stable name links are written with
    release: str


def read_kit(home: Path) -> Kit:
    """The installed kit. Never installs one."""
    root = kithome.current_release(home)
    if root is None:
        raise DevkitError(
            f"no installed kit at {kithome.current_link(home)}",
            "run ./install.py --profile core --apply from the kit checkout first; "
            "devkit project only reads an installed kit")
    stamp = kithome.read_stamp(root) or {}
    return Kit(root, kithome.current_link(home), str(stamp.get("release_id") or root.name))


# -------------------------------------------------------------------- git

def _git(repo: Path, *args: str) -> str:
    try:
        proc = subprocess.run(["git", "--literal-pathspecs", "-C", str(repo), *args],
                              capture_output=True, text=True, check=False)
    except FileNotFoundError:
        raise DevkitError("git is not on PATH", "install git, then re-run") from None
    if proc.returncode:
        raise DevkitError(f"git {args[0]} failed in {repo}: {proc.stderr.strip()}")
    return proc.stdout


def require_repo(path: str | os.PathLike[str]) -> Path:
    repo = Path(path).resolve()
    if not (repo / ".git").exists():
        raise DevkitError(f"{repo} is not the root of a git work tree",
                          "run it from the repo root, or pass the root as PATH")
    return repo


def tracked_among(repo: Path, paths: list[str]) -> set[str]:
    """Tracked files at or under any of `paths` (repo-relative)."""
    if not paths:
        return set()
    out = _git(repo, "ls-files", "-z", "--", *paths)
    return {p for p in out.split("\0") if p}


def _git_path(repo: Path, *args: str) -> Path:
    path = Path(_git(repo, "rev-parse", *args).strip())
    return path if path.is_absolute() else repo / path


def exclude_path(repo: Path) -> Path:
    """The exclude file git reads for this work tree. A linked worktree shares
    the common dir's file with every other worktree."""
    return _git_path(repo, "--git-path", "info/exclude")


def worktree_id(repo: Path) -> str:
    gitdir = _git_path(repo, "--git-dir").resolve()
    common = _git_path(repo, "--git-common-dir").resolve()
    return "main" if gitdir == common else f"worktree {gitdir.name}"


def _markers(wid: str) -> tuple[str, str]:
    return f"# >>> devkit project {wid} >>>", f"# <<< devkit project {wid} <<<"


def write_exclude_block(path: Path, wid: str, entries: list[str], plan: Plan) -> None:
    """Make this worktree's block hold exactly `entries`; touch nothing else.

    Foreign lines and other worktrees' blocks are kept. An empty list removes
    the block. An unchanged block is not rewritten.
    """
    start, end = _markers(wid)
    lines = path.read_text(encoding="utf-8").splitlines() if path.is_file() else []
    block = [start, *(f"/{e}" for e in entries), end] if entries else []
    if start in lines:
        first = lines.index(start)
        if end not in lines[first + 1:]:
            raise DevkitError(f"{path}: the {start!r} block has no closing marker",
                              "remove the dangling marker line by hand, then re-run")
        last = lines.index(end, first + 1)
        new = lines[:first] + block + lines[last + 1:]
    else:
        new = lines + block
    if new == lines:
        return
    plan.record(f"exclude {path} ({len(entries)} entries)" if entries
                else f"exclude {path} (remove block)")
    if plan.apply:
        ensure_dir(path.parent)
        path.write_text("\n".join(new) + "\n" if new else "", encoding="utf-8")


# ----------------------------------------------------------------- stamp

def read_stamp(repo: Path) -> dict | None:
    try:
        data = json.loads((repo / STAMP_REL).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    return data if isinstance(data, dict) else None


def _sha(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


# ---------------------------------------------------------------- planner

@dataclass(frozen=True)
class Action:
    kind: str           # link | relink | write | prune | warn
    rel: str
    target: str = ""    # link target
    content: str = ""   # file content
    note: str = ""

    def line(self) -> str:
        if self.kind in ("link", "relink"):
            return f"{self.kind:<6s} {self.rel} -> {self.target}"
        return f"{self.kind:<6s} {self.rel}" + (f": {self.note}" if self.note else "")


@dataclass
class BuildPlan:
    actions: list[Action] = field(default_factory=list)
    entries: list[str] = field(default_factory=list)    # generated and excluded
    stamp: dict = field(default_factory=dict)
    shadowed: list[str] = field(default_factory=list)

    @property
    def changes(self) -> list[Action]:
        return [a for a in self.actions if a.kind != "warn"]


def _own_skills(repo: Path) -> set[str]:
    root = repo / OWN_SKILLS_REL
    if not root.is_dir():
        return set()
    return {c.name for c in root.iterdir() if c.is_dir() and not c.name.startswith(".")}


def _ours_target(rel: str, target: str, link_prefix: str) -> bool:
    """Does a link at `rel` point where a build puts it?"""
    name = rel.rsplit("/", 1)[-1]
    if rel.startswith(AGENTS_SKILLS + "/"):
        return (target.startswith(link_prefix + "/")
                or target == f"../../{OWN_SKILLS_REL}/{name}")
    if rel.startswith(CLAUDE_SKILLS + "/"):
        return target == f"../../{AGENTS_SKILLS}/{name}"
    return rel == INSTRUCTIONS_LINK and target == INSTRUCTIONS


class _Ctx:
    def __init__(self, repo: Path, tracked: set[str], prior: dict | None,
                 link_prefix: str) -> None:
        self.repo = repo
        self.tracked = tracked
        self.prior_entries = set((prior or {}).get("entries", []))
        self.link_prefix = link_prefix
        self.blocked = [d for d in _GUARDED_DIRS
                        if os.path.lexists(repo / d)
                        and ((repo / d).is_symlink() or not (repo / d).is_dir())]

    def is_tracked(self, rel: str) -> bool:
        return rel in self.tracked or any(t.startswith(rel + "/") for t in self.tracked)

    def blocked_by(self, rel: str) -> str | None:
        return next((d for d in self.blocked if rel.startswith(d + "/")), None)

    def decide(self, rel: str, target: str) -> tuple[str, str]:
        """(outcome, reason): outcome is ok, link, relink or warn."""
        path = self.repo / rel
        if (parent := self.blocked_by(rel)):
            return "warn", f"{parent} is a link or a file, not a directory"
        if self.is_tracked(rel):
            if path.is_symlink() and os.readlink(path) == target:
                return "ok", ""
            return "warn", "tracked in git, left alone"
        if not os.path.lexists(path):
            return "link", ""
        if not path.is_symlink():
            return "warn", "exists and is not a link the build made, left alone"
        current = os.readlink(path)
        if current == target:
            return "ok", ""
        if rel in self.prior_entries or _ours_target(rel, current, self.link_prefix):
            return "relink", ""
        return "warn", f"a link to {current} that the build did not create, left alone"


def _render_rules(kit: Kit, resolved: Resolved) -> str:
    script = kit.root / "core" / "bin" / "generate-agents-md.py"
    layers = ["core"] + (["client"] if "client" in resolved.lineage else [])
    argv = [sys.executable, str(script), "--stdout"]
    for layer in layers:
        argv += ["--layer", layer]
    proc = subprocess.run(argv, capture_output=True, text=True, check=False)
    if proc.returncode:
        raise DevkitError(f"the rules generator failed: {proc.stderr.strip()}",
                          "run it by hand to see the error: " + " ".join(argv))
    return proc.stdout


def _instructions(repo: Path, kit: Kit, resolved: Resolved, with_rules: bool) -> str | None:
    parts: list[str] = []
    own = repo / OWN_INSTRUCTIONS_REL
    if own.is_file():
        text = own.read_text(encoding="utf-8")
        if text.strip():
            parts.append(text.rstrip("\n") + "\n")
    if with_rules:
        parts.append(_render_rules(kit, resolved))
    if not parts:
        return None
    return GENERATED_HEADER + "\n" + "\n---\n\n".join(parts)


def plan_build(repo: Path, config: Config, kit: Kit, with_rules: bool,
               prior: dict | None = None) -> BuildPlan:
    """What a build would do. Reads the repo and the kit; writes nothing."""
    resolved = resolve_layers(config.layers, kit.root)
    own = _own_skills(repo)
    base = [s for s in resolved.skills if s not in own]
    names = sorted(set(base) | own)
    link_prefix = str(kit.link / "core" / "skills")

    candidates = [STAMP_REL, INSTRUCTIONS, INSTRUCTIONS_LINK]
    candidates += [f"{d}/{n}" for n in names for d in (AGENTS_SKILLS, CLAUDE_SKILLS)]
    for d in (AGENTS_SKILLS, CLAUDE_SKILLS):
        if (repo / d).is_dir() and not (repo / d).is_symlink():
            candidates += [f"{d}/{c.name}" for c in (repo / d).iterdir()]
    # `git ls-files` refuses a path beyond a link, and a guarded dir that is a
    # link is skipped anyway.
    probe = _Ctx(repo, set(), prior, link_prefix)
    queried = [c for c in dict.fromkeys(candidates) if probe.blocked_by(c) is None]
    ctx = _Ctx(repo, tracked_among(repo, queried), prior, link_prefix)

    plan = BuildPlan(shadowed=sorted(set(resolved.skills) & own))
    entries: set[str] = set()
    wanted: set[str] = set()

    def place(rel: str, target: str, excluded: bool) -> bool:
        wanted.add(rel)
        outcome, reason = ctx.decide(rel, target)
        if outcome == "warn":
            plan.actions.append(Action("warn", rel, note=reason))
            return False
        if outcome != "ok":
            plan.actions.append(Action(outcome, rel, target=target))
        if excluded and not ctx.is_tracked(rel):
            entries.add(rel)
        return True

    for name in plan.shadowed:
        plan.actions.append(Action(
            "warn", f"{AGENTS_SKILLS}/{name}",
            note=f"{OWN_SKILLS_REL}/{name} wins over the base skill of the same name"))
    for name in names:
        is_own = name in own
        a_target = (f"../../{OWN_SKILLS_REL}/{name}" if is_own
                    else f"{link_prefix}/{name}")
        if place(f"{AGENTS_SKILLS}/{name}", a_target, excluded=not is_own):
            place(f"{CLAUDE_SKILLS}/{name}", f"../../{AGENTS_SKILLS}/{name}",
                  excluded=not is_own)

    for d in (AGENTS_SKILLS, CLAUDE_SKILLS):
        directory = repo / d
        if not directory.is_dir() or directory.is_symlink():
            continue
        for child in sorted(directory.iterdir()):
            rel = f"{d}/{child.name}"
            if rel in wanted or not child.is_symlink() or ctx.is_tracked(rel):
                continue
            if rel in ctx.prior_entries or _ours_target(rel, os.readlink(child), link_prefix):
                plan.actions.append(Action("prune", rel))

    agents_md = _plan_instructions(repo, kit, resolved, with_rules, prior, ctx, plan, entries)

    plan.entries = sorted(entries)
    plan.stamp = {
        "schema": SCHEMA, "release": kit.release, "layers": list(config.layers),
        "rules": with_rules, "entries": plan.entries,
        "agents_md": agents_md is not None, "agents_md_sha256": agents_md,
    }
    if ctx.is_tracked(STAMP_REL):
        raise DevkitError(f"{STAMP_REL} is tracked in git",
                          f"untrack it (git rm --cached {STAMP_REL}) or do not build here")
    stamp_text = json.dumps(plan.stamp, indent=2) + "\n"
    stamp_file = repo / STAMP_REL
    if not stamp_file.is_file() or stamp_file.read_text(encoding="utf-8") != stamp_text:
        plan.actions.append(Action("write", STAMP_REL, content=stamp_text))
    return plan


def _plan_instructions(repo: Path, kit: Kit, resolved: Resolved, with_rules: bool,
                       prior: dict | None, ctx: _Ctx, plan: BuildPlan,
                       entries: set[str]) -> str | None:
    """AGENTS.md and the CLAUDE.md link. Returns the sha256 of AGENTS.md when
    the build owns it, else None."""
    content = _instructions(repo, kit, resolved, with_rules)
    agents, claude = repo / INSTRUCTIONS, repo / INSTRUCTIONS_LINK
    ours = bool(prior and prior.get("agents_md") and agents.is_file()
                and not agents.is_symlink() and not ctx.is_tracked(INSTRUCTIONS)
                and _sha(agents.read_text(encoding="utf-8")) == prior.get("agents_md_sha256"))

    if ours:
        if content is None:
            plan.actions.append(Action("prune", INSTRUCTIONS))
            if claude.is_symlink() and os.readlink(claude) == INSTRUCTIONS:
                plan.actions.append(Action("prune", INSTRUCTIONS_LINK))
            return None
    else:
        exists = any(os.path.lexists(p) or ctx.is_tracked(r)
                     for p, r in ((agents, INSTRUCTIONS), (claude, INSTRUCTIONS_LINK)))
        if exists:
            if content is not None:
                plan.actions.append(Action(
                    "warn", INSTRUCTIONS,
                    note="AGENTS.md or CLAUDE.md already exists, instructions not written"))
            return None
        if content is None:
            return None

    if not agents.is_file() or agents.read_text(encoding="utf-8") != content:
        plan.actions.append(Action("write", INSTRUCTIONS, content=content))
    entries.add(INSTRUCTIONS)
    outcome, reason = ctx.decide(INSTRUCTIONS_LINK, INSTRUCTIONS)
    if outcome == "warn":
        plan.actions.append(Action("warn", INSTRUCTIONS_LINK, note=reason))
    else:
        if outcome != "ok":
            plan.actions.append(Action(outcome, INSTRUCTIONS_LINK, target=INSTRUCTIONS))
        entries.add(INSTRUCTIONS_LINK)
    return _sha(content)


def _apply_actions(repo: Path, actions: list[Action], plan: Plan) -> None:
    for action in actions:
        if action.kind == "warn":
            continue
        plan.record(action.line())
        if not plan.apply:
            continue
        path = repo / action.rel
        if action.kind in ("link", "relink"):
            ensure_dir(path.parent)
            if path.is_symlink():
                path.unlink()
            path.symlink_to(action.target)
        elif action.kind == "write":
            ensure_dir(path.parent)
            path.write_text(action.content, encoding="utf-8")
            path.chmod(FILE_MODE)
        elif action.kind == "prune":
            path.unlink()


def _print_warnings(actions: list[Action]) -> None:
    for action in actions:
        if action.kind == "warn":
            print(f"warn  {action.rel}: {action.note}")


# --------------------------------------------------------------- commands

def _home(args) -> Path:
    return Path(privilege.refuse_root(getattr(args, "user", None)).pw_dir)


def cmd_build(args) -> int:
    home = _home(args)
    repo = require_repo(args.path)
    kit = read_kit(home)
    config = load_config(repo, getattr(args, "config", None))
    prior = read_stamp(repo)
    rules = getattr(args, "rules", None)
    if rules is None:
        rules = bool((prior or {}).get("rules"))
    built = plan_build(repo, config, kit, rules, prior)
    plan = Plan(args.apply)
    # The exclude block goes first so a generated path is never untracked-visible.
    write_exclude_block(exclude_path(repo), worktree_id(repo),
                        [*built.entries, STAMP_REL], plan)
    _print_warnings(built.actions)
    _apply_actions(repo, built.changes, plan)
    return plan.report(f"project {repo.name}")


def _would_be_empty(directory: Path, removed: set[Path]) -> bool:
    return directory.is_dir() and not directory.is_symlink() and all(
        child in removed for child in directory.iterdir())


def _clean_is_ours(rel: str, path: Path, stamp: dict, link_prefix: str) -> bool:
    if rel == INSTRUCTIONS:
        return (path.is_file() and not path.is_symlink() and stamp.get("agents_md")
                and _sha(path.read_text(encoding="utf-8")) == stamp.get("agents_md_sha256"))
    if not path.is_symlink():
        return False
    target = os.readlink(path)
    name = rel.rsplit("/", 1)[-1]
    if rel.startswith(AGENTS_SKILLS + "/"):
        return target == f"{link_prefix}/{name}"
    return _ours_target(rel, target, link_prefix)


def cmd_clean(args) -> int:
    home = _home(args)
    repo = require_repo(args.path)
    stamp = read_stamp(repo)
    if stamp is None:
        print(f"project {repo.name}: no {STAMP_REL}, nothing to clean.")
        return 0
    link_prefix = str(kithome.current_link(home) / "core" / "skills")
    entries = [e for e in stamp.get("entries", []) if isinstance(e, str)]
    tracked = tracked_among(repo, [*entries, STAMP_REL])
    plan = Plan(args.apply)
    removed: set[Path] = set()

    for rel in sorted(entries):
        path = repo / rel
        if not os.path.lexists(path):
            continue
        if rel in tracked:
            print(f"warn  {rel}: tracked in git, left alone")
        elif _clean_is_ours(rel, path, stamp, link_prefix):
            plan.record(f"unlink {rel}")
            removed.add(path)
            if plan.apply:
                path.unlink()
        else:
            print(f"warn  {rel}: no longer what the build wrote, left alone")

    write_exclude_block(exclude_path(repo), worktree_id(repo), [], plan)
    if (repo / STAMP_REL).exists() and STAMP_REL not in tracked:
        plan.record(f"unlink {STAMP_REL}")
        removed.add(repo / STAMP_REL)
        if plan.apply:
            (repo / STAMP_REL).unlink()
    for rel in _PRUNE_DIRS:
        directory = repo / rel
        if _would_be_empty(directory, removed):
            plan.record(f"rmdir  {rel}")
            removed.add(directory)
            if plan.apply:
                directory.rmdir()
    return plan.report(f"project {repo.name} (clean)")


def _profile_skills() -> tuple[str, set[str]]:
    agents_home = os.environ.get("AGENTS_HOME")
    if not agents_home:
        return "", set()
    skills = Path(agents_home) / "skills"
    names = {c.name for c in skills.iterdir()} if skills.is_dir() else set()
    return os.environ.get("DEVKIT_PROFILE") or agents_home, names


def cmd_status(args) -> int:
    home = _home(args)
    repo = require_repo(args.path)
    stamp = read_stamp(repo)
    if stamp is None:
        print(f"project {repo.name}: not built. Run: devkit project build {repo} --apply")
        return 1
    kit = read_kit(home)
    config = load_config(repo, getattr(args, "config", None))
    built = plan_build(repo, config, kit, bool(stamp.get("rules")), stamp)

    problems = [a.line() for a in built.changes
                if not (a.rel == STAMP_REL and _same_but_release(built.stamp, stamp))]
    for rel in stamp.get("entries", []):
        path = repo / rel
        if path.is_symlink() and not path.exists():
            problems.append(f"broken {rel} -> {os.readlink(path)}")

    built_from, installed = stamp.get("release"), kit.release
    note = "" if built_from == installed else f" (kit is now {installed}; informational)"
    print(f"project {repo.name}: built from kit release {built_from}{note}")
    _print_warnings(built.actions)
    profile, profile_skills = _profile_skills()
    project_skills = {rel.rsplit("/", 1)[-1] for rel in built.entries
                      if rel.startswith(AGENTS_SKILLS + "/")} | _own_skills(repo)
    for name in sorted(project_skills & profile_skills):
        print(f"warn  skill {name}: the active profile ({profile}) also provides it")
    if problems:
        print(f"{len(problems)} problem(s); run: devkit project build {repo} --apply")
        for problem in problems:
            print(f"  {problem}")
        return 1
    print("ok")
    return 0


def _same_but_release(new: dict, old: dict) -> bool:
    return {k: v for k, v in new.items() if k != "release"} == {
        k: v for k, v in old.items() if k != "release"}


def cmd_init(args) -> int:
    home = _home(args)
    repo = require_repo(args.path)
    layers = list(dict.fromkeys(args.layer or []))
    if not layers:
        raise DevkitError("no layers given", "pass --layer <profile type>, e.g. --layer core")
    kit = read_kit(home)
    for layer in layers:
        if not _NAME.match(layer):
            raise DevkitError(f"{layer!r} is not a profile type name")
        manifest.load(layer, kit_root=kit.root)
    target = repo / CONFIG_REL
    if target.exists() and not getattr(args, "force", False):
        raise DevkitError(f"{CONFIG_REL} already exists in {repo}",
                          "re-run with --force to overwrite it")
    plan = Plan(args.apply)
    plan.record(f"write  {CONFIG_REL} (layers: {', '.join(layers)})")
    if plan.apply:
        write_json(target, {"schema": SCHEMA, "layers": layers})
    return plan.report(f"project {repo.name} (init)")
