#!/usr/bin/env python3
"""Generate rules/AGENTS.md from rules/manifest.json.

AGENTS.md is the single instruction file Claude Code and Codex ingest. It was
hand-maintained alongside the Cursor `.mdc` rules, so the two drifted silently
(plan devkit, A0/B2). This makes it generated, and gives a profile a rule
list it can filter by layer instead of a 668-line file it must edit by hand.

Each section names its body source:

  body.from == "mdc"   embed that rule file verbatim; frontmatter and the H1 are
                       stripped and headings are demoted one level. Editing the
                       .mdc is the only way to change the section.
  body.from == "file"  the AGENTS.md text is a translation of a rule, or a merge
                       of several. It lives in agents.d/ as its single source.

Usage:
    generate-agents-md.py                 # dry run: report what would change
    generate-agents-md.py --check         # exit 1 if AGENTS.md is out of date
    generate-agents-md.py --apply         # write AGENTS.md
    generate-agents-md.py --layer core    # only core sections (drop the client overlay)
    generate-agents-md.py --stdout        # print the render

Exit codes: 0 = up to date or written, 1 = drift (--check) or error, 2 = bad invocation.

Python 3.12, standard library only.
"""

from __future__ import annotations

import argparse
import difflib
import json
import re
import sys
from pathlib import Path

RULES_DIR = Path(__file__).resolve().parent.parent / "rules"
MANIFEST = RULES_DIR / "manifest.json"
OUTPUT = RULES_DIR / "AGENTS.md"
CLAUDE_DIR = RULES_DIR / "claude"
BASE_MDC = RULES_DIR / "BASE.mdc"
BASE_MDC_FRONTMATTER = (
    "---\n"
    "description: Execution contract — precise model (constitution for all vendors)\n"
    "alwaysApply: true\n"
    "---\n\n"
)
CLAUDE_NOTICE = "<!-- Generated by bin/generate-agents-md.py from rules/manifest.json; do not edit. -->"


class GenerateError(Exception):
    """A manifest or body file is missing or malformed."""


def read_body_file(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8").strip()
    except OSError as exc:
        raise GenerateError(f"cannot read {path}: {exc}") from exc


def mdc_text(path: Path) -> str:
    """Rule body with frontmatter and H1 stripped, headings at their own level."""
    text = read_body_file(path)
    front = re.match(r"^---\n.*?\n---\n", text, re.DOTALL)
    if front:
        text = text[front.end():].strip()
    lines = text.split("\n")
    if lines and lines[0].startswith("# "):
        lines = lines[1:]
    return "\n".join(lines).strip()


def mdc_body(path: Path) -> str:
    """Rule body with frontmatter and H1 stripped and headings demoted one level.

    Demotion is what lets a rule's own `## Do` sit under the `##` section heading
    AGENTS.md gives it. Fenced blocks are left alone so a `#` comment in a shell
    sample is not mistaken for a heading.
    """
    return demote(mdc_text(path)).strip()


def demote(text: str) -> str:
    """Every heading one level down; fenced `#` comments are not headings."""
    out, in_fence = [], False
    for line in text.split("\n"):
        if line.lstrip().startswith("```"):
            in_fence = not in_fence
        if not in_fence and re.match(r"^#{1,5} ", line):
            line = "#" + line
        out.append(line)
    return "\n".join(out)


def section_text(section: dict, *, nested: bool = True) -> str:
    """nested: the body sits under a `##` section title, so a rule's own `##` moves down a level."""
    body = section["body"]
    if body["from"] == "mdc":
        path = RULES_DIR / body["file"]
        return mdc_body(path) if nested else mdc_text(path)
    if body["from"] == "file":
        return read_body_file(RULES_DIR / "agents.d" / body["file"])
    raise GenerateError(f"{section['title']}: unknown body.from {body['from']!r}")


def active_sections(manifest: dict, layers: set[str] | None) -> list[dict]:
    return [s for s in manifest["sections"] if layers is None or s.get("layer", "core") in layers]


def slugify(title: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")


def render_claude_dir(manifest: dict, layers: set[str] | None) -> dict[str, str]:
    """One .md per section, for ~/.claude/rules: Claude reads a rules dir, not AGENTS.md."""
    files = {"00-base.md": f"{CLAUDE_NOTICE}\n\n{read_body_file(RULES_DIR / manifest['base']['file'])}\n"}
    if manifest.get("notes"):
        files["01-notes.md"] = f"{CLAUDE_NOTICE}\n\n# Notes\n\n{read_body_file(RULES_DIR / manifest['notes'])}\n"
    for number, section in enumerate(active_sections(manifest, layers), start=2):
        name = f"{number:02d}-{slugify(section['title'])}.md"
        files[name] = f"{CLAUDE_NOTICE}\n\n# {section['title']}\n\n{section_text(section, nested=False)}\n"
    return files


def render_base_mdc(manifest: dict) -> str:
    """Cursor's copy of BASE.md: same body behind rule frontmatter, so edits happen in one file."""
    return BASE_MDC_FRONTMATTER + read_body_file(RULES_DIR / manifest["base"]["file"]) + "\n"


def render(manifest: dict, layers: set[str] | None) -> str:
    parts = [read_body_file(RULES_DIR / manifest["intro"]), ""]
    if manifest.get("notes"):
        parts += [read_body_file(RULES_DIR / manifest["notes"]), ""]
    # One H1 for the whole file: BASE and the sections sit one level under the intro's title.
    parts += ["---", "", demote(read_body_file(RULES_DIR / manifest["base"]["file"])), "",
              "---", "", "## Operational rules", ""]

    for section in active_sections(manifest, layers):
        parts += [f"### {section['title']}", "", demote(section_text(section)), ""]

    if manifest.get("trailer"):
        parts.append(read_body_file(RULES_DIR / manifest["trailer"]))
    return "\n".join(parts).rstrip("\n") + "\n"


def load_manifest() -> dict:
    try:
        manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    except OSError as exc:
        raise GenerateError(f"cannot read {MANIFEST}: {exc}") from exc
    except ValueError as exc:
        raise GenerateError(f"{MANIFEST} is not valid JSON: {exc}") from exc
    for key in ("base", "intro", "sections"):
        if key not in manifest:
            raise GenerateError(f"{MANIFEST} is missing the {key!r} key")
    return manifest


def main() -> int:
    parser = argparse.ArgumentParser(
        prog="generate-agents-md.py",
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--apply", action="store_true", help="Write AGENTS.md, the Claude rules folder and BASE.mdc.")
    mode.add_argument("--check", action="store_true", help="Exit 1 if AGENTS.md, the Claude rules folder or BASE.mdc is out of date.")
    mode.add_argument("--stdout", action="store_true", help="Print the render and write nothing.")
    parser.add_argument("--claude-dir", type=Path, default=CLAUDE_DIR,
                        help="Folder for the per-section Claude rules (default: rules/claude).")
    parser.add_argument("--layer", action="append", metavar="LAYER",
                        help="Keep only sections in this layer (repeatable). Default: all.")
    args = parser.parse_args()

    layers = set(args.layer) if args.layer else None
    try:
        manifest = load_manifest()
        rendered = render(manifest, layers)
        claude_files = render_claude_dir(manifest, layers)
    except GenerateError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    if args.stdout:
        sys.stdout.write(rendered)
        return 0

    claude_dir = args.claude_dir
    base_mdc = render_base_mdc(manifest)
    base_mdc_current = BASE_MDC.read_text(encoding="utf-8") if BASE_MDC.exists() else ""
    current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
    # Only files carrying the notice are ours: a hand-written rule in a target folder is never compared or removed.
    on_disk = {p.name: p.read_text(encoding="utf-8") for p in claude_dir.glob("*.md")} if claude_dir.is_dir() else {}
    on_disk = {name: text for name, text in on_disk.items() if text.startswith(CLAUDE_NOTICE)}
    if rendered == current and claude_files == on_disk and base_mdc == base_mdc_current:
        print(f"{OUTPUT} and {claude_dir} are up to date.")
        return 0

    diff = list(difflib.unified_diff(
        current.splitlines(), rendered.splitlines(),
        f"{OUTPUT.name} (on disk)", f"{OUTPUT.name} (generated)", lineterm="", n=2))
    diff += list(difflib.unified_diff(
        base_mdc_current.splitlines(), base_mdc.splitlines(),
        "BASE.mdc (on disk)", "BASE.mdc (generated)", lineterm="", n=2))
    for name in sorted(set(on_disk) | set(claude_files)):
        diff += list(difflib.unified_diff(
            on_disk.get(name, "").splitlines(), claude_files.get(name, "").splitlines(),
            f"{claude_dir.name}/{name} (on disk)", f"{claude_dir.name}/{name} (generated)", lineterm="", n=2))

    if args.apply:
        OUTPUT.write_text(rendered, encoding="utf-8")
        BASE_MDC.write_text(base_mdc, encoding="utf-8")
        claude_dir.mkdir(parents=True, exist_ok=True)
        for stale in set(on_disk) - set(claude_files):
            (claude_dir / stale).unlink()
        for name, text in claude_files.items():
            (claude_dir / name).write_text(text, encoding="utf-8")
        print(f"Wrote {OUTPUT} and {len(claude_files)} files in {claude_dir} ({len(diff)} diff lines).")
        return 0

    print("\n".join(diff))
    verb = "is out of date" if args.check else "would change"
    print(f"\n{OUTPUT}, {claude_dir} or BASE.mdc {verb}. Run: {Path(__file__).name} --apply", file=sys.stderr)
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
