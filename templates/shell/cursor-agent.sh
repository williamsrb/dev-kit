#!/bin/sh
# Tier 1 wrapper for cursor-agent, profile ${PROFILE_NAME}.
#
# cursor-agent has no config-dir flag of its own. It reads XDG_CONFIG_HOME for
# config and CURSOR_DATA_DIR for sessions (measured 2026-09-18).
#
# XDG_CONFIG_HOME is a GENERIC variable: exporting it would relocate the config
# directory of every XDG-aware program in this shell. So it is set on the exec
# line only, scoped to this one process, and never exported. That is why this
# wrapper is shaped differently from the Claude and Codex ones.
#
# DEVKIT_PROFILE / AGENTS_HOME / PATH are exported: child tools (agentctl)
# must inherit the profile, and PATH alone is not enough for that.
#
# Generated by devkit; edits are lost on `devkit profile sync`.
set -eu
DEVKIT_PROFILE="${PROFILE_NAME}"
export DEVKIT_PROFILE
DEVKIT_PROFILE_HOME="${PROFILE_HARNESS_DIR}"
export DEVKIT_PROFILE_HOME
AGENTS_HOME="${PROFILE_AGENTS_HOME}"
export AGENTS_HOME
PATH="${PROFILE_BIN_DIR}:${PATH}"
export PATH
# graft writes .gitignore and .ignore into every repo it builds in; the kit
# ships those patterns in the global git ignore instead.
GRAFT_NO_GITIGNORE=1
GRAFT_NO_IGNORE=1
export GRAFT_NO_GITIGNORE GRAFT_NO_IGNORE
exec env \
  XDG_CONFIG_HOME="${PROFILE_XDG_CONFIG_DIR}" \
  CURSOR_DATA_DIR="${PROFILE_DATA_DIR}" \
  CURSOR_WORKTREES_ROOT="${PROFILE_DATA_DIR}/worktrees" \
  "${PROFILE_CURSOR_AGENT}" "$@"
